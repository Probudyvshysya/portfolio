def stroka(i, op):
    data, summa, kredit, ka, inn, kat, naz = op
    inn = KLIENTY.get(ka, "") if inn is None else inn
    s = f"{summa:.2f}".replace(".", ",")
    return [data, SCHET, f"{1000 + i}", s, "Кредит" if kredit else "Дебет",
            ka if kredit else "", "" if kredit else ka, inn, kat, naz, ""]


def zapisat(imya, nomera):
    with open(PAPKA / imya, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(SHAPKA)
        for i in nomera:
            w.writerow(stroka(i, OPERACII[i]))


