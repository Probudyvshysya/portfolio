def main() -> None:
    KIT.mkdir(parents=True, exist_ok=True)
    LIB.mkdir(parents=True, exist_ok=True)

    doc = Docx()
    doc.add_heading("Техническое задание (учебное)", 1)
    for line in TZ_CLAUSES:
        doc.add_paragraph(line)
    table = doc.add_table(rows=2, cols=2)
    table.cell(0, 0).text, table.cell(0, 1).text = "Объём", "Срок"
    table.cell(1, 0).text, table.cell(1, 1).text = "2,4 км", "45 дней"
    doc.save(KIT / "tz.docx")

    # «скан» — картинка в PDF без текстового слоя: светофор обязан покраснеть
    img = Image.new("RGB", (1240, 1754), "white")
    ImageDraw.Draw(img).text((120, 120), "SMETA (scan, no text layer)", fill="black")
    img.save(KIT / "smeta_scan.pdf", "PDF", resolution=150)

    for name, text in NORMS.items():
        (LIB / name).write_text(text, encoding="utf-8")
    (HERE / "registry.json").write_text(json.dumps(REGISTRY, ensure_ascii=False, indent=2), encoding="utf-8")
    (HERE / "rules.json").write_text(json.dumps(RULES, ensure_ascii=False, indent=2), encoding="utf-8")
    (HERE / "journal.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in JOURNAL), encoding="utf-8")
    print("учебный комплект собран:", KIT, LIB)


if __name__ == "__main__":
    main()
